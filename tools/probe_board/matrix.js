'use strict';

//
//  Render the probe board fixtures as the tables in docs/terminal-compatibility.md.
//
//    node tools/probe_board/matrix.js            print the tables
//    node tools/probe_board/matrix.js --write    replace them in the doc
//
//  The doc keeps hand-written text outside the markers; only the part between
//  them is generated, and a test fails when it no longer matches the fixtures.
//

const fs = require('fs');
const path = require('path');

const { analyze } = require('./analyze');
const { Probes } = require('./probes');

const FIXTURES = path.join(__dirname, '..', '..', 'test', 'fixtures', 'probe_board');
const DOC = path.join(__dirname, '..', '..', 'docs', 'terminal-compatibility.md');
const START = '<!-- probe-matrix:start (generated by tools/probe_board/matrix.js; edit outside the markers) -->';
const END = '<!-- probe-matrix:end -->';

//  Column order and display names, by fixture file name.
const TERMINALS = [
    [ 'syncterm',   'SyncTERM' ],
    [ 'terminator', 'TERMinator 1.1.3' ],
    [ 'icyterm',    'IcyTerm 0.9.2' ],
    [ 'netrunner',  'NetRunner' ],
    [ 'telnet-exe', 'Windows telnet.exe' ],
    [ 'telix',      'Telix 3.51' ],
    [ 'pcplus',     'Procomm Plus TD' ],
    [ 'terminate',  'Terminate 5.00' ],
    [ 'telemate',   'Telemate 4.21' ],
    [ 'qmodem',     'Qmodem 4.6' ],
    [ 'procomm',    'Procomm 2.4.3' ],
];

const esc = s => s.replace(/\|/g, '\\|');
const code = s => `\`${esc(s)}\``;

function loadAll(dir = FIXTURES) {
    return TERMINALS
        .filter(([ file ]) => fs.existsSync(path.join(dir, `${file}.json`)))
        .map(([ file, name ]) => {
            const report = JSON.parse(fs.readFileSync(path.join(dir, `${file}.json`), 'utf8'));
            return { file, name, summary : analyze(report) };
        });
}

function probeCell(p) {
    if (!p) {
        return '';
    }
    const got = [ ...p.replies, ...p.cprs ];
    const parts = got.map(code);
    if (p.printed) {
        parts.unshift(`**P${p.printedCols || '?'}**`);
    }
    if (!p.complete) {
        parts.push('(timed out)');
    }
    return parts.join(' ') || '·';
}

function sizeCell(s, key) {
    const v = s.size[key];
    if (!v) {
        return '·';
    }
    const flags = v.flags && v.flags.length ? ` (${v.flags.join(', ')})` : '';
    return `${v.cols}x${v.rows}${flags}`;
}

function render(rows = loadAll()) {
    const head = `| | ${rows.map(r => r.name).join(' | ')} |`;
    const rule = `|---|${rows.map(() => '---').join('|')}|`;
    const line = (label, fn) => `| ${label} | ${rows.map(r => fn(r.summary)).join(' | ')} |`;

    const ident = [
        head, rule,
        line('TTYPE', s => s.telnet.ttypes.map(code).join(', ') || 'none'),
        line('NAWS', s => {
            const n = s.telnet.naws;
            if (!n) {
                return 'none';
            }
            const what = n.malformed ? `malformed: ${code(n.hex)}`
                : n.truncated8 ? `${n.width}x${n.height}, high byte dropped`
                    : !n.plausible ? `${n.width}x${n.height}, implausible` : `${n.width}x${n.height}`;
            return what;
        }),
        line('Identified as', s => {
            const d = s.identity.da1;
            if (!d) {
                return 'nothing (no DA reply)';
            }
            return d.client ? `${d.client} ${d.version || ''}`.trim() : (d.vtClass || code(d.raw));
        }),
        line('Cursor reports', s => {
            const c = s.cpr;
            if ('normal' === c.kind && !c.rowOffset && !c.colOffset) {
                return 'normal';
            }
            const off = c.rowOffset ? ` row ${c.rowOffset > 0 ? '+' : ''}${c.rowOffset}` : '';
            return `${c.kind}${off}`;
        }),
        line('`999;999` + CPR', s => sizeCell(s, 'size-999')),
        line('`CSI 255 n`', s => sizeCell(s, 'size-255n')),
        line('Size to use', s => `**${s.size.recommended.cols}x${s.size.recommended.rows}** (${s.size.recommended.source})`),
    ];

    const probeRows = [ head, rule ];
    for (const def of Probes) {
        if ('baseline' === def.id) {
            continue;
        }
        probeRows.push(`| ${code(def.id)}<br>${esc(def.about)} | ${rows.map(r => probeCell(r.summary.probes.find(p => def.id === p.id))).join(' | ')} |`);
    }

    return [
        START,
        '',
        '### Identification and size',
        '',
        ...ident,
        '',
        '### Every probe',
        '',
        'A cell lists what came back: replies, then any cursor report the probe itself caused.',
        '**P*n*** means the probe was printed as text, moving the cursor *n* columns. · means no reply and nothing printed.',
        '',
        ...probeRows,
        '',
        END,
    ].join('\n');
}

function replaceIn(doc, tables) {
    const a = doc.indexOf(START);
    const b = doc.indexOf(END);
    if (a < 0 || b < a) {
        throw new Error(`markers not found in ${DOC}`);
    }
    return doc.slice(0, a) + tables + doc.slice(b + END.length);
}

module.exports = { render, replaceIn, loadAll, DOC, START, END };

if (require.main === module) {
    const tables = render();
    if (process.argv.includes('--write')) {
        fs.writeFileSync(DOC, replaceIn(fs.readFileSync(DOC, 'utf8'), tables));
        console.log(`updated ${DOC}`);
    } else {
        console.log(tables);
    }
}
